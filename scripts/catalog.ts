import { writeFileSync } from "node:fs"
import vocab from "../data/vocab.json" with { type: "json" }
import districts from "../data/districts.json" with { type: "json" }
import { departmentLabel, labelize } from "../src/lib/labels.ts"

/**
 * Writes docs/what-is-recorded.md: every kind, desk and service a person can document, the fields on each
 * entity, and why each one is an Arkiv attribute or is deliberately left off chain. The tables come from
 * data/vocab.json, so the document cannot drift from what the guard accepts.  npm run catalog
 */
const v = vocab as {
  departments: { slug: string; label: string }[]
  kinds: { slug: string; label: string }[]
  roles: Record<string, string[]>
  services: Record<string, string[]>
  conditions: Record<string, Record<string, string[]>>
  outcomes: { slug: string; label: string }[]
  geoServices: Record<string, string[]>
}

const list = (slugs: string[]) => slugs.map((slug) => `\`${slug}\` (${labelize(slug)})`).join(", ")
const demandRows = Object.entries(v.services)
  .map(([dept, services]) => `| ${departmentLabel(dept)} (\`${dept}\`) | ${v.roles[dept].map((r) => `\`${r}\``).join(", ")} | ${list(services)} |`)
  .join("\n")

const conditionTable = (kind: string) =>
  Object.entries(v.conditions[kind])
    .map(([dept, services]) => `| ${departmentLabel(dept)} (\`${dept}\`) | ${list(services)} |`)
    .join("\n")

const count = (o: Record<string, string[]>) => Object.values(o).reduce((n, a) => n + a.length, 0)
const demandServices = count(v.services)
const conditionServices = Object.values(v.conditions).reduce((n, o) => n + count(o), 0)
const stateCount = districts.states.length
const districtCount = districts.states.reduce((n, s) => n + s.districts.length, 0)
const pinnable = Object.entries(v.geoServices).flatMap(([d, s]) => s.map((x) => `${departmentLabel(d)} · ${labelize(x)}`))

const doc = `# What can be recorded, and why it lives on Arkiv

Generated by \`npm run catalog\` from [data/vocab.json](../data/vocab.json) and [data/districts.json](../data/districts.json). The guard, the reader and the audit use the same two files, so this list is exactly what the app accepts. Anything else is refused before it is written, and ignored by every reader if someone writes it straight to the chain.

**${v.kinds.length} kinds, ${v.departments.length} departments, ${demandServices + conditionServices} services, ${stateCount} states and union territories, ${districtCount} districts.** Nothing is typed as free text. A person picks from lists, and the lists contain no names.

## 1. The five kinds

| Kind | What it records | The number on it | Example |
| --- | --- | --- | --- |
| \`demand\` | Money asked for a routine public service | Rupees asked, 1 to 10,000,000 | "The RTO asked ₹700 for a driving licence" |
| \`failure\` | A public thing that is broken | Severity 1 to 5 | "A pothole on the main road, severity 4" |
| \`absence\` | Something that should be there and is not | Severity 1 to 5 | "No doctor at the primary health centre" |
| \`diversion\` | Something meant for the public that did not arrive | Severity 1 to 5 | "Ration grain short by weight" |
| \`restriction\` | A right that an authority restricted or violated | Severity 1 to 5 | "Mobile internet cut for a district", "journalist detained" |

Severity is one scale for every non-demand kind: **1** minor, **2** limited, **3** clearly reported with local impact or an order enforced, **4** many people for days or a mass detention, **5** a death or serious harm. A rupee amount is never averaged with a severity: \`kind\` is part of the bucket.

## 2. Demands: what a bribe report can name

A demand names a desk, never a person. The role is a job title from the list, and only titles valid for that department are accepted.

| Department | Roles | Services |
| --- | --- | --- |
${demandRows}

Outcomes for a demand: ${v.outcomes
  .slice(0, 3)
  .map((o) => `\`${o.slug}\` (${o.label})`)
  .join(", ")}.

## 3. Failures: broken public things

| Department | Services |
| --- | --- |
${conditionTable("failure")}

## 4. Absences: what is missing

| Department | Services |
| --- | --- |
${conditionTable("absence")}

## 5. Diversions: what did not arrive

| Department | Services |
| --- | --- |
${conditionTable("diversion")}

## 6. Rights violations and shutdowns

Added 17 October 2026, because corruption and a closed network are the same failure seen from two sides: a public servant used a public power for something other than the public. These are about **what an authority did to a gathering, a person's freedom, the press, a home or the network**. Nobody is named, no unit is named, and the place is the district.

| Department | Services |
| --- | --- |
${conditionTable("restriction")}

Outcomes for every non-demand kind: ${v.outcomes
  .slice(3)
  .map((o) => `\`${o.slug}\` (${o.label})`)
  .join(", ")}.

## 7. The fields on every entity

Every report is one Arkiv entity with fourteen possible attributes and a fixed payload. Everything below is public. The *Why this is an attribute* column is the reason it is on Arkiv and not in a table behind our server.

| Field | Who supplies it | Example | Why this is an attribute |
| --- | --- | --- | --- |
| \`project\` | The app | \`underthetable\` | Arkiv is one shared chain; every query starts with it so we only read our own rows |
| \`type\` | The app | \`report\` or \`attestation\` | Two entity types in one query, told apart with no second round trip |
| \`state\` | The person (district picker) | \`mh\` | Equality query, and the reader checks the district belongs to it |
| \`district\` | The person (district picker) | \`nashik\` | The unit of the whole product; "everything in this district" is one predicate |
| \`department\` | The person (or the sentence parser) | \`rto\` | Equality query, and the role and service must belong to it |
| \`role\` | The person | \`motor_vehicle_inspector\` | A job title from a closed list, never a name |
| \`service\` | The person | \`driving_licence\` | The desk that is quoted |
| \`outcome\` | The person | \`paid\` | Whether the demand was met, or whether the condition changed |
| \`kind\` | The person | \`demand\` | Keeps rupees and severity apart |
| \`week\` | The person picks a week; the app writes the ISO week | \`2026-W42\` | The only date on chain. A day plus a district plus a service can identify a reporter, so the day is never stored |
| \`amount_inr\` | The person | \`700\` (rupees) or \`3\` (severity) | The one numeric field, because range queries only work on numbers (\`u64\`) |
| \`lat_e5\`, \`lon_e5\` | The person, optional | \`1999751\`, \`7378981\` | \`i32\` degrees times 100,000, only for broken public infrastructure, so "pins in this rectangle" is four range predicates answered by the chain |
| \`source\` | A curator wallet only | \`press\` | Believed only when \`$creator\` is in the curator list |
| \`day\` | Nobody (legacy) | | Old rows only; never written now |

And two fields Arkiv itself gives us, which a table of ours would have to fake:

| Arkiv field | What we use it for |
| --- | --- |
| \`$creator\` | A wallet is one voice; three distinct wallets are needed to quote a number. It cannot be forged by a writer: the chain sets it. A checker wallet's attestations and the press curator's rows are trusted by \`$creator\`, not by anything the writer typed |
| \`$owner\` | Handed to \`0x…dEaD\` in the same batch that creates the entity, so the writer, and we, cannot delete or edit it. The page and \`npm run audit\` check it on every row |
| Entity Expiration | 180 days. A report leaves queries on its own, with no job of ours and no delete button; the creation transaction stays on the explorer |

The payload is the bytes \`{"v":1}\` and nothing else. No story, no photo, no name, no hash.

## 8. Optional extras on a report

- **A location check.** If the person allows one position read, a separate checker wallet writes an \`attestation\` entity that says only "this wallet was inside this state when it filed". The position is never stored, only the word "inside". It makes a report *checked*; three checked wallets on one desk make it *corroborated*.
- **A pin.** Only for ${pinnable.join(", ")}. The person drops a pin on the broken thing, or taps "use my current location". The pin is the place of the problem, not of the person. It is rejected for any other kind: a bribe, a detention or a shutdown is never pinned, because an exact place and a week could identify someone.
- **A human check.** Before a new throwaway key is funded with test GLM, the browser proves it is driven by a person: Cloudflare Turnstile when the host has the keys, otherwise a proof of work signed by the server. This is not on chain, and it is not claimed to prove that a wallet is a unique person.

## 9. What is never recorded

A name, a phone number, an email, an address, a street, a case or FIR number, a photograph, a document, a free-text story, a precise time, a device or network address, or the position of the person who reported. The sentence box is parsed on the device and never sent. A tripwire (digits in Hindi and Latin, UPI handles, spelled-out emails, honorifics and names that follow them) takes private details out of what it reads, and the writer refuses a slip that still contains one.

## 10. Why this belongs on Arkiv, in one table

| What the record needs | Postgres behind our API | IPFS | A subgraph | Arkiv |
| --- | --- | --- | --- | --- |
| Nobody, including us, can edit or delete a row later | Admin can \`UPDATE\` or \`DELETE\` | Immutable, but no query and no expiry | Indexes a chain that holds the data elsewhere | \`readonly\` plus a dead \`$owner\`, checked by anyone |
| Anyone can ask "all rows for this district" | Only through our endpoint | No | Yes, through our subgraph | An equality query on a public node |
| A number range ("severity at least 3", "inside this box") | Yes, on our server | No | Yes, if we write the mapping | \`gte\`/\`lte\` on \`u64\` and \`i32\` attributes, answered by the chain's own index |
| The record leaves on its own after a fixed time | A cron job we must keep running | Pinned forever, or unpinned by us | No | Entity Expiration, 180 days, no job |
| The writer's identity cannot be forged by the writer | A column the writer fills in | A CID has no creator | Event data only | \`$creator\`, set by the chain |
| It is still there when our server is gone | No | Only if someone pins it | The index is gone | Yes, and a one-file mirror reads it with no server of ours |

The longer argument, with the commands to reproduce each row, is in [docs/arkiv-usage.md](arkiv-usage.md) and [docs/submission.md](submission.md).
`

writeFileSync("docs/what-is-recorded.md", doc)
console.log(`wrote docs/what-is-recorded.md (${demandServices + conditionServices} services, ${districtCount} districts)`)
